#!/bin/sh
# Prints CHANGELOG.md, built from conventional commit subjects between version tags.
# Usage: scripts/changelog.sh [next-version]
# With a version, commits after the latest tag are listed under that version, dated today.
# Without one, they are listed under "Unreleased". The file is generated: never edit it by hand.
set -eu

repo_url="https://github.com/apurv-1/trackedge"
next="${1:-}"

# Prints one release section for the commits in a git revision range.
section() {
    title="$1"
    range="$2"
    log=$(git log --no-merges --format='%s' "$range")
    [ -n "$log" ] || return 0

    printf '## %s\n\n' "$title"
    printf '%s\n' "$log" | awk '
        {
            subject = $0
            type = subject
            sub(/[(:!].*/, "", type)
            breaking = (subject ~ /^[a-z]+(\([^)]*\))?!:/)
            sub(/^[a-z]+(\([^)]*\))?!?: */, "", subject)
            if (breaking) group = "Breaking changes"
            else if (type == "feat") group = "Features"
            else if (type == "fix") group = "Fixes"
            else if (type == "perf") group = "Performance"
            else if (type == "docs") group = "Documentation"
            else group = "Maintenance"
            items[group] = items[group] "- " toupper(substr(subject, 1, 1)) substr(subject, 2) "\n"
        }
        END {
            split("Breaking changes|Features|Fixes|Performance|Documentation|Maintenance", order, "|")
            for (i = 1; i <= 6; i++) {
                if (order[i] in items) printf "### %s\n\n%s\n", order[i], items[order[i]]
            }
        }'
}

printf '# Changelog\n\n'
printf '<!-- Generated by scripts/changelog.sh from commit messages. Do not edit by hand. -->\n\n'
printf 'All notable changes to TrackEdge. Versions follow [Semantic Versioning](https://semver.org).\n\n'

tags=$(git tag --list 'v[0-9]*.[0-9]*.[0-9]*' --sort=-v:refname)
latest=$(printf '%s\n' "$tags" | head -n 1)

head_range="${latest:+$latest..}HEAD"
if [ -n "$next" ]; then
    section "[$next]($repo_url/releases/tag/v$next) - $(date -u +%Y-%m-%d)" "$head_range"
else
    section "Unreleased" "$head_range"
fi

previous_tags=$(printf '%s\n' "$tags" | sed 1d)
for tag in $tags; do
    older=$(printf '%s\n' "$previous_tags" | head -n 1)
    previous_tags=$(printf '%s\n' "$previous_tags" | sed 1d)
    date=$(git log -1 --format=%cs "$tag")
    section "[${tag#v}]($repo_url/releases/tag/$tag) - $date" "${older:+$older..}$tag"
done
